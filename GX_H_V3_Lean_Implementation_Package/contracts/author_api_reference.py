"""Reference-only Author API shapes; derive final API from science_grid@2 migration."""
from typing import Any, Mapping, Protocol

class WorkflowRegistrar(Protocol):
    def register(self, *, workflow_id: str, version: str, hooks: Any) -> None: ...

class ToolRegistrar(Protocol):
    def register(self, *, name: str, schema: Mapping[str, Any], handler: Any) -> None: ...

class CapabilityRegistrar(Protocol):
    def add_manifest(self, manifest_bundle_ref: str) -> None:
        """Use existing Capability Registry/Governance; no duplicate registry."""
        ...

class TaskAPI(Protocol):
    def read_context(self, task_id: str) -> Mapping[str, Any]: ...
    def propose(self, spec: Mapping[str, Any], *, idempotency_key: str) -> Mapping[str, Any]: ...

class JobAPI(Protocol):
    def inspect_capability(self, capability_id: str, version: str) -> Mapping[str, Any]: ...
    def propose(self, proposal: Mapping[str, Any], *, idempotency_key: str) -> Mapping[str, Any]: ...
    def wait(self, job_id: str) -> Mapping[str, Any]: ...
    def cancel(self, job_id: str, *, reason: str, idempotency_key: str) -> Mapping[str, Any]: ...

class ArtifactAPI(Protocol):
    def read(self, artifact_ref: str) -> Mapping[str, Any]: ...
    def publish(self, spec: Mapping[str, Any], *, idempotency_key: str) -> Mapping[str, Any]: ...

class EvaluationAPI(Protocol):
    def propose(self, spec: Mapping[str, Any], *, idempotency_key: str) -> Mapping[str, Any]: ...

class PluginContext(Protocol):
    """Run-bound; hook contexts may be transaction-bound. Never expose raw conn/SQL."""
    workflows: WorkflowRegistrar
    tools: ToolRegistrar
    capabilities: CapabilityRegistrar
    tasks: TaskAPI
    jobs: JobAPI
    artifacts: ArtifactAPI
    evaluations: EvaluationAPI

def register(ctx: PluginContext) -> None: ...
